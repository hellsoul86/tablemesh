test('room ownership, private views, duplicate/stale/concurrent actions, complete hand and second hand', async t => {
  const f = await fixture(); t.after(f.close);
  const room = await twoPlayerRoom(f);
  const outsider = await f.register('观众');
  const aView = (await room.a.request(`/rooms/${room.id}`)).body.data;
  const bView = (await room.b.request(`/rooms/${room.id}`)).body.data;
  assert.equal(aView.you.privateState.holeCards.length, 2);
  assert.equal(bView.you.privateState.holeCards.length, 2);
  for (const card of bView.you.privateState.holeCards) assert.equal(JSON.stringify(aView).includes(`"${card}"`), false);
  const observation = await outsider.request(`/rooms/${room.id}`);
  assert.equal(observation.body.data.you.privateState, null);
  assert.deepEqual(observation.body.data.you.legalActions, []);
  assert.equal(JSON.stringify(observation.body).includes('deck'), false);
  const events = await outsider.request(`/rooms/${room.id}/events?after=0`);
  for (const card of [...aView.you.privateState.holeCards, ...bView.you.privateState.holeCards]) assert.equal(JSON.stringify(events.body.data.events).includes(`"${card}"`), false);
  assert.equal((await room.b.request(`/rooms/${room.id}/start`, { stateVersion: aView.stateVersion, requestId: randomUUID() })).status, 403);
  assert.equal((await room.a.request(`/rooms/${room.id}/leave`, { stateVersion: aView.stateVersion, requestId: randomUUID() })).status, 409);
  const actor = aView.game.actorSeat === aView.you.seat ? room.a : room.b;
  const other = actor === room.a ? room.b : room.a;
  const own = actor === room.a ? aView : bView;
  const action = { type: own.you.legalActions.some(move => move.type === 'check') ? 'check' : 'call' };
  const payload = { stateVersion: own.stateVersion, windowId: own.game.window.id, requestId: randomUUID(), action };
  assert.equal((await other.request(`/rooms/${room.id}/actions`, payload)).body.ok, false);
  assert.equal((await actor.request(`/rooms/${room.id}/actions`, { ...payload, accountId: other.account.id })).body.error.code, 'INVALID_INPUT');
  const accepted = await actor.request(`/rooms/${room.id}/actions`, payload);
  assert.equal(accepted.body.ok, true);
  const repeated = await actor.request(`/rooms/${room.id}/actions`, payload);
  assert.equal(repeated.body.data.replayed, true);
  assert.equal(repeated.body.data.snapshot.stateVersion, accepted.body.data.snapshot.stateVersion);
  assert.equal((await actor.request(`/rooms/${room.id}/actions`, { ...payload, action: { type: 'fold' } })).body.error.code, 'REQUEST_ID_CONFLICT');
  assert.equal((await actor.request(`/rooms/${room.id}/actions`, { ...payload, requestId: randomUUID() })).body.error.code, 'VERSION_CONFLICT');
  const now = (await other.request(`/rooms/${room.id}`)).body.data;
  const currentActor = now.you.legalActions.length ? other : actor;
  const current = (await currentActor.request(`/rooms/${room.id}`)).body.data;
  const move = current.you.legalActions.some(move => move.type === 'check') ? 'check' : 'call';
  const concurrent = await Promise.all([1, 2].map(() => currentActor.request(`/rooms/${room.id}/actions`, { stateVersion: current.stateVersion, windowId: current.game.window.id, requestId: randomUUID(), action: { type: move } })));
  assert.equal(concurrent.filter(result => result.body.ok).length, 1);
  assert.equal(concurrent.find(result => !result.body.ok).body.error.code, 'VERSION_CONFLICT');
  const done = await finishHand(room);
  assert.equal(done.game.phase, 'complete');
  assert.equal(done.game.seats.reduce((sum, seat) => sum + seat.stack, 0), 2000);
  const history = (await room.a.request(`/rooms/${room.id}/events?after=0`)).body.data.events.filter(event => event.type === 'hand_settled');
  assert.equal(history.length, 1);
  assert.equal(history[0].payload.participants.length, 2);
  assert.equal(JSON.stringify(history[0]).includes('holeCards'), false);
  assert.equal(JSON.stringify(history[0]).includes('deck'), false);
  assert.equal((await room.a.request('/account')).body.data.points, 1000);
  assert.equal((await room.b.request('/account')).body.data.points, 1000);
  assert.equal((await room.a.request(`/rooms/${room.id}/start`, { stateVersion: done.stateVersion, requestId: randomUUID() })).body.ok, true);
});

test('seat races, folded-card isolation on slot replacement, and same-room stack retention', async t => {
  const f = await fixture(); t.after(f.close);
  const room = await twoPlayerRoom(f);
  const first = room.snapshot.game.actorSeat === room.snapshot.you.seat ? room.a : room.b;
  const own = (await first.request(`/rooms/${room.id}`)).body.data;
  const hidden = own.you.privateState.holeCards;
  const folded = await first.request(`/rooms/${room.id}/actions`, { stateVersion: own.stateVersion, windowId: own.game.window.id, requestId: randomUUID(), action: { type: 'fold' } });
  assert.equal(folded.body.data.snapshot.game.phase, 'complete');
  assert.deepEqual(folded.body.data.snapshot.game.revealedHands, []);
  const stack = folded.body.data.snapshot.game.seats.find(seat => seat.accountId === first.account.id).stack;
  const leave = await first.request(`/rooms/${room.id}/leave`, { stateVersion: folded.body.data.snapshot.stateVersion, requestId: randomUUID() });
  assert.equal(leave.body.ok, true);
  const c = await f.register('丙'); const d = await f.register('丁');
  const joinPayload = { seat: own.you.seat, stateVersion: leave.body.data.snapshot.stateVersion, requestId: randomUUID() };
  const race = await Promise.all([c.request(`/rooms/${room.id}/join`, joinPayload), d.request(`/rooms/${room.id}/join`, { ...joinPayload, requestId: randomUUID() })]);
  assert.equal(race.filter(result => result.body.ok).length, 1);
  const newcomer = race[0].body.ok ? c : d;
  const joined = race.find(result => result.body.ok).body.data.snapshot;
  assert.deepEqual(joined.you.privateState.holeCards, []);
  for (const card of hidden) assert.equal(JSON.stringify(joined).includes(`"${card}"`), false);
  const newcomerLeave = await newcomer.request(`/rooms/${room.id}/leave`, { stateVersion: joined.stateVersion, requestId: randomUUID() });
  const rejoined = await first.request(`/rooms/${room.id}/join`, { seat: own.you.seat, stateVersion: newcomerLeave.body.data.snapshot.stateVersion, requestId: randomUUID() });
  assert.equal(rejoined.body.ok, true);
  assert.equal(rejoined.body.data.snapshot.game.seats.find(seat => seat.accountId === first.account.id).stack, stack);
});

test('process restart preserves private state, sessions, deadlines, cursors, and applies overdue fold once', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'tablemesh-restart-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  let now = 100_000;
  const config = { databasePath: join(directory, 'test.sqlite'), inventoryKey: randomBytes(32), now: () => now };
  let f = await fixture(config);
  const room = await twoPlayerRoom(f, { ...defaultRoomConfig, turnTimeoutMs: 1000 });
  const before = (await room.a.request(`/rooms/${room.id}`)).body.data;
  await f.close();
  f = await fixture(config);
  const restored = await f.client(room.a.cookie).request(`/rooms/${room.id}`);
  assert.equal(restored.body.data.stateVersion, before.stateVersion);
  assert.equal(restored.body.data.eventCursor, before.eventCursor);
  assert.deepEqual(restored.body.data.you.privateState, before.you.privateState);
  assert.deepEqual(restored.body.data.game.window, before.game.window);
  now = before.game.window.deadline;
  await f.app.runTimeouts();
  const after = (await f.client(room.a.cookie).request(`/rooms/${room.id}`)).body.data;
  assert.equal(after.game.phase, 'complete');
  assert.equal(after.stateVersion, before.stateVersion + 1);
  assert.equal((await f.client(room.a.cookie).request('/account')).body.data.fairPlay.reputation, 100);
  const results = (await f.client(room.a.cookie).request(`/rooms/${room.id}/events?after=0`)).body.data.events.filter(event => event.type === 'hand_settled');
  assert.equal(results.length, 1);
  assert.equal(results[0].payload.participants.length, 2);
  await f.app.runTimeouts();
  assert.equal((await f.client(room.a.cookie).request(`/rooms/${room.id}`)).body.data.stateVersion, after.stateVersion);
  await f.close();
  f = await fixture(config);
  const preserved = (await f.client(room.a.cookie).request(`/rooms/${room.id}/events?after=0`)).body.data.events.filter(event => event.type === 'hand_settled');
  assert.deepEqual(preserved, results);
  assert.equal(f.app.store.all('SELECT * FROM hand_settlements WHERE room_id=?', room.id).length, 1);
  await f.close();
});

test('expired credentials fail and timeout checks rather than spending chips when checking is legal', async t => {
  let now = 200_000;
  const f = await fixture({ now: () => now, sessionTtlMs: 100_000, gameTokenTtlMs: 1000 }); t.after(f.close);
  const room = await twoPlayerRoom(f, { ...defaultRoomConfig, turnTimeoutMs: 1000 });
  let view = (await room.a.request(`/rooms/${room.id}`)).body.data;
  for (let i = 0; view.game.phase === 'preflop'; i++) {
    assert.ok(i < 5);
    const actor = view.game.actorSeat === 0 ? room.a : room.b;
    const own = (await actor.request(`/rooms/${room.id}`)).body.data;
    const type = own.you.legalActions.some(move => move.type === 'check') ? 'check' : 'call';
    view = (await actor.request(`/rooms/${room.id}/actions`, { stateVersion: own.stateVersion, windowId: own.game.window.id, requestId: randomUUID(), action: { type } })).body.data.snapshot;
  }
  const stacks = view.game.seats.map(seat => seat.stack);
  now = view.game.window.deadline;
  await f.app.runTimeouts();
  const checked = (await room.a.request(`/rooms/${room.id}`)).body.data;
  assert.deepEqual(checked.game.seats.map(seat => seat.stack), stacks);
  assert.equal(checked.stateVersion, view.stateVersion + 1);
  const minted = await room.a.request('/auth/tokens', { label: 'expiry' });
  now += 1000;
  assert.equal((await f.client('', minted.body.data.token).request('/account')).status, 401);
  now += 100_000;
  assert.equal((await room.a.request('/account')).status, 401);
});

test('encrypted inventory, atomic final-stock redemption, idempotency, balance and owner-only reveal', async t => {
  const f = await fixture(); t.after(f.close);
  const a = await f.register(); const b = await f.register();
  const code = 'SANDBOX-NO-VALUE-' + randomUUID();
  const product = { id: 'sandbox', name: '无价值测试卡', pointsCost: 100, sandbox: true };
  const imported = await f.admin.request('/ops/inventory', { product, codes: [code], requestId: 'import1' });
  assert.equal(imported.body.data.imported, 1);
  assert.equal((await f.admin.request('/ops/inventory', { product, codes: [code], requestId: 'import1' })).body.data.imported, 1);
  assert.equal((await f.admin.request('/ops/inventory', { product, codes: [code], requestId: 'duplicate' })).body.ok, false);
  assert.equal(JSON.stringify(f.app.store.all('SELECT * FROM inventory')).includes(code), false);
  assert.equal(JSON.stringify(f.app.store.all('SELECT * FROM requests')).includes(code), false);
  const results = await Promise.all([a.request('/rewards/redemptions', { productId: product.id, requestId: 'redeem' }), b.request('/rewards/redemptions', { productId: product.id, requestId: 'redeem' })]);
  assert.equal(results.filter(result => result.body.ok).length, 1);
  assert.equal(results.find(result => !result.body.ok).body.error.code, 'OUT_OF_STOCK');
  const winner = results[0].body.ok ? a : b;
  const loser = winner === a ? b : a;
  const order = results.find(result => result.body.ok).body.data;
  assert.equal(order.status, 'fulfilled');
  assert.equal('code' in order, false);
  assert.equal((await winner.request('/account')).body.data.points, 900);
  assert.equal((await loser.request('/account')).body.data.points, 1000);
  const repeated = await winner.request('/rewards/redemptions', { productId: product.id, requestId: 'redeem' });
  assert.equal(repeated.body.data.id, order.id);
  assert.equal((await winner.request('/account')).body.data.points, 900);
  assert.equal((await winner.request('/rewards/redemptions', { productId: 'other', requestId: 'redeem' })).body.error.code, 'REQUEST_ID_CONFLICT');
  const entries = (await winner.request('/points')).body.data.entries;
  assert.equal(entries.reduce((sum, entry) => sum + entry.delta, 0), 900);
  assert.equal(entries.reduce((sum, entry) => sum + entry.heldDelta, 0), 0);
  assert.equal(entries.length, 3);
  assert.equal((await loser.request(`/rewards/redemptions/${order.id}`)).status, 404);
  const secret = await winner.request(`/rewards/redemptions/${order.id}`);
  assert.equal(secret.body.data.code === code, true);
  assert.equal(secret.cache, 'no-store');
  assert.equal(JSON.stringify((await winner.request('/rewards/redemptions')).body).includes(code), false);
  const minted = await winner.request('/auth/tokens', { label: 'no rewards' });
  assert.equal((await f.client('', minted.body.data.token).request(`/rewards/redemptions/${order.id}`)).status, 403);
  assert.equal((await f.admin.request('/ops/inventory', { product: { ...product, id: 'real', sandbox: false }, codes: ['REAL-NOT-IMPORTED'], requestId: randomUUID() })).body.error.code, 'REWARDS_DISABLED');
});

